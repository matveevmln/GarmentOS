/** Нормализация под ключ справочника: регистр, пробелы и ё → е
 *  («Чёрный», «чёрный», «ЧЕРНЫЙ» — один и тот же цвет). */
function normalize(color: string): string {
  return color.trim().toLowerCase().replace(/ё/g, "е");
}

/** hex образца или null, если цвет не из справочника. */
export function colorSwatch(color: string): string | null {
  return SWATCHES[normalize(color)] ?? null;
}
